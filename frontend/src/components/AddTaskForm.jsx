import React, { useState } from "react";
import axios from "axios";

export default function AddTaskForm() {
  const [title, setTitle] = useState("");
  const [description, setDescription] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const generateDescription = async () => {
    if (!title.trim()) {
      setError("Please enter a task title first.");
      return;
    }
    setLoading(true);
    setError("");
    try {
      const resp = await axios.post(
        "http://localhost:5000/api/generate-description",
        { title, details: description }
      );
      setDescription(resp.data.description);
    } catch (e) {
      console.error(e);
      setError(
        "AI service unavailable – please write the description yourself."
      );
    } finally {
      setLoading(false);
    }
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    console.log("Submitting task:", { title, description });
    // TODO: send to your own /api/tasks endpoint
    setTitle("");
    setDescription("");
  };

  return (
    <form onSubmit={handleSubmit} style={{ maxWidth: "500px", margin: "auto" }}>
      <h2>Add / Create Task</h2>

      <label>
        <strong>Title</strong>
        <br />
        <input
          type="text"
          value={title}
          onChange={(e) => setTitle(e.target.value)}
          placeholder="e.g. Build landing page"
          required
          style={{ width: "100%", padding: "0.5rem", marginTop: "0.3rem" }}
        />
      </label>

      <br />
      <br />

      <label>
        <strong>Description</strong>
        <br />
        <textarea
          rows={4}
          value={description}
          onChange={(e) => setDescription(e.target.value)}
          placeholder="Task details (optional – can be generated by AI)"
          style={{ width: "100%", padding: "0.5rem", marginTop: "0.3rem" }}
        />
      </label>

      <br />
      <br />

      <button
        type="button"
        onClick={generateDescription}
        disabled={loading}
        style={{
          background: "#0066ff",
          color: "#fff",
          border: "none",
          padding: "0.6rem 1.2rem",
          cursor: loading ? "not-allowed" : "pointer",
          marginRight: "0.5rem",
        }}
      >
        {loading ? "Generating…" : "Generate with AI"}
      </button>

      {error && (
        <p style={{ color: "red", marginTop: "0.5rem" }}>{error}</p>
      )}

      <br />

      <button
        type="submit"
        style={{
          background: "#28a745",
          color: "#fff",
          border: "none",
          padding: "0.6rem 1.2rem",
          cursor: "pointer",
        }}
      >
        Save Task
      </button>
    </form>
  );
}
